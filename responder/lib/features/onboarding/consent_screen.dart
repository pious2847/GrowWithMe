import 'package:flutter/material.dart';

import '../../core/api_client.dart';
import '../../core/theme/app_colors.dart';
import '../../core/ui/app_widgets.dart';
import 'onboarding_frame.dart';
import 'profile_screen.dart';

/// Registration step 1 — privacy & confidentiality agreement. Responders see
/// real patient data (names, phone numbers, danger signs, live location), so
/// before anything else they must understand and accept their duties.
/// The backend refuses profile registration until this is signed.
class ConsentScreen extends StatefulWidget {
  const ConsentScreen({super.key, required this.user});

  final Map<String, dynamic> user;

  @override
  State<ConsentScreen> createState() => _ConsentScreenState();
}

class _ConsentScreenState extends State<ConsentScreen> {
  bool _confidentiality = false;
  bool _dataProcessing = false;
  bool _busy = false;
  String? _error;

  bool get _ready => _confidentiality && _dataProcessing;

  Future<void> _accept() async {
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      final res = await Api.I.dio.post('/responder/profile', data: {
        'consent': {
          'patientConfidentiality': true,
          'dataProcessing': true,
        },
      });
      final user = res.data['user'] as Map<String, dynamic>;
      if (!mounted) return;
      Navigator.of(context).pushReplacement(
          MaterialPageRoute(builder: (_) => ProfileScreen(user: user)));
    } catch (_) {
      if (!mounted) return;
      setState(() => _error =
          'Could not save your agreement. Check your connection and try again.');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final t = Theme.of(context).textTheme;
    return OnboardingFrame(
      step: 1,
      title: 'Your duty starts\nwith trust.',
      subtitle: 'You will see a mother’s name, her phone number, her danger '
          'signs and where she is. That access is a privilege — read this '
          'before you continue.',
      footer: Column(
        children: [
          if (_error != null) ...[
            Text(
              _error!,
              style: const TextStyle(
                fontFamily: 'Manrope',
                fontSize: 12.5,
                fontWeight: FontWeight.w600,
                color: AppColors.coral,
              ),
            ),
            const SizedBox(height: 10),
          ],
          LimeButton(
            label: _ready
                ? 'I agree — continue'
                : 'Tick both promises to continue',
            icon: Icons.arrow_forward_rounded,
            busy: _busy,
            onPressed: _ready && !_busy ? _accept : null,
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          SurfaceCard(
            padding: const EdgeInsets.all(18),
            gradient: AppColors.heroGradient,
            borderColor: AppColors.forestDeep,
            child: Row(
              children: [
                Container(
                  width: 50,
                  height: 50,
                  decoration: BoxDecoration(
                    color: AppColors.lime.withValues(alpha: 0.15),
                    borderRadius: BorderRadius.circular(16),
                  ),
                  child: const Icon(Icons.shield_rounded,
                      color: AppColors.lime, size: 26),
                ),
                const SizedBox(width: 14),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Protected patient data',
                        style: t.titleSmall?.copyWith(
                          color: AppColors.cream,
                          fontSize: 15,
                        ),
                      ),
                      const SizedBox(height: 4),
                      Text(
                        'Access is logged. Breaking confidentiality ends your '
                        'access and may be reported.',
                        style: t.bodySmall?.copyWith(
                          color: AppColors.cream.withValues(alpha: 0.72),
                          height: 1.4,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 16),
          _DutySection(
            icon: Icons.visibility_rounded,
            title: 'What you will see',
            points: const [
              'Patient names, phone numbers, reported danger signs and location — only for urgent cases routed to you.',
              'Health risk reports generated by the GrowWithMe app.',
            ],
          ),
          _DutySection(
            icon: Icons.task_alt_rounded,
            title: 'What you must do',
            points: const [
              'Use patient information only to respond to that case.',
              'Keep everything confidential — like hospital medical records.',
              'Contact a patient only about their own case.',
              'Report to the patient’s facility, not on social media.',
            ],
          ),
          _DutySection(
            icon: Icons.block_rounded,
            title: 'What you must never do',
            accent: AppColors.coral,
            points: const [
              'Share, screenshot or post patient information anywhere.',
              'Use a patient’s phone number or location for anything other than their case.',
              'Claim a professional tier (nurse, midwife, doctor) you do not hold — false credentials lead to removal and may be reported to the authorities.',
            ],
          ),
          _DutySection(
            icon: Icons.lock_rounded,
            title: 'How your data is protected',
            accent: AppColors.teal,
            points: const [
              'Your ID documents and live location are encrypted in transit and stored securely; location is used only to route nearby cases to you.',
              'Handled in line with Ghana’s Data Protection Act, 2012 (Act 843) and HIPAA-style health-privacy safeguards.',
              'Access to patient data is logged. Breaking these rules ends your access.',
            ],
          ),
          const SizedBox(height: 4),
          Text(
            'YOUR PROMISE',
            style: t.labelSmall?.copyWith(
              color: AppColors.muted,
              fontSize: 10,
              letterSpacing: 1.6,
            ),
          ),
          const SizedBox(height: 10),
          CheckRow(
            value: _confidentiality,
            onChanged: (v) => setState(() => _confidentiality = v),
            text: 'I will keep all patient information confidential and use '
                'it only to provide care.',
          ),
          const SizedBox(height: 10),
          CheckRow(
            value: _dataProcessing,
            onChanged: (v) => setState(() => _dataProcessing = v),
            text: 'I consent to my ID documents and live location being '
                'processed to verify me and route urgent cases.',
          ),
        ],
      ),
    );
  }
}

class _DutySection extends StatelessWidget {
  const _DutySection({
    required this.icon,
    required this.title,
    required this.points,
    this.accent = AppColors.forest,
  });

  final IconData icon;
  final String title;
  final List<String> points;
  final Color accent;

  @override
  Widget build(BuildContext context) {
    final t = Theme.of(context).textTheme;
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: SurfaceCard(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                IconBubble(
                  icon: icon,
                  color: accent,
                  size: 34,
                  iconSize: 18,
                ),
                const SizedBox(width: 10),
                Expanded(child: Text(title, style: t.titleSmall)),
              ],
            ),
            const SizedBox(height: 12),
            for (final point in points)
              Padding(
                padding: const EdgeInsets.only(bottom: 8),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Padding(
                      padding: const EdgeInsets.only(top: 7),
                      child: Container(
                        width: 5,
                        height: 5,
                        decoration: BoxDecoration(
                          color: accent.withValues(alpha: 0.65),
                          shape: BoxShape.circle,
                        ),
                      ),
                    ),
                    const SizedBox(width: 10),
                    Expanded(
                      child: Text(
                        point,
                        style: t.bodySmall?.copyWith(
                          color: AppColors.inkSoft,
                          height: 1.5,
                        ),
                      ),
                    ),
                  ],
                ),
              ),
          ],
        ),
      ),
    );
  }
}
