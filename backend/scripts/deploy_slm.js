async function deploy() {
  console.log('==============================================');
  console.log(' GrowWithMe Nana SLM Deployment');
  console.log('==============================================');

  try {
    // --------------------------------------------------------
    // 1. Check ZIP
    // --------------------------------------------------------

    console.log('\nChecking model package...');

    const info = calculateFileInfo(ZIP_PATH);

    console.log(`ZIP: ${info.zipPath}`);
    console.log(
      `Size: ${(info.sizeBytes / 1024 / 1024).toFixed(2)} MB`
    );
    console.log(`SHA256: ${info.sha256}`);

    // --------------------------------------------------------
    // 2. Build manifest
    // --------------------------------------------------------

    const manifest = {
      name: MODEL_NAME,

      // version is automatically determined below
      kind: 'llm',

      url: HUGGINGFACE_URL,

      sha256: info.sha256,

      sizeBytes: info.sizeBytes,

      active: true,

      meta: {
        trainedOn:
          'Llama 3.2 on 55k synthetic maternal health conversations',

        disclaimer:
          'Fine-tuned SLM on-device adapter.',

        source:
          'Hugging Face - abdulhafis/growwithme-nana-slm',

        file:
          'nana_slm_v1.zip',
      },
    };

    // --------------------------------------------------------
    // 3. Publish to LOCAL MongoDB
    // --------------------------------------------------------

    console.log('\n----------------------------------------------');
    console.log('Publishing to local MongoDB');
    console.log('----------------------------------------------');

    await publishToDatabase(localDbUri, manifest);

    // --------------------------------------------------------
    // 4. Publish to MongoDB Atlas
    // --------------------------------------------------------

    console.log('\n----------------------------------------------');
    console.log('Publishing to MongoDB Atlas');
    console.log('----------------------------------------------');

    await publishToDatabase(remoteDbUri, manifest);

    // --------------------------------------------------------
    // 5. Done
    // --------------------------------------------------------

    console.log('\n==============================================');
    console.log(' DEPLOYMENT COMPLETE');
    console.log('==============================================');

    console.log('\nModel URL:');
    console.log(HUGGINGFACE_URL);

    console.log('\nSHA256:');
    console.log(info.sha256);

    console.log(
      `\nPackage size: ${(info.sizeBytes / 1024 / 1024).toFixed(2)} MB`
    );

  } catch (error) {
    console.error('\n==============================================');
    console.error(' DEPLOYMENT FAILED');
    console.error('==============================================');

    console.error(error);

    process.exit(1);
  }
}

