function calculateFileInfo(filePath) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`ZIP file not found: ${filePath}`);
  }

  const buffer = fs.readFileSync(filePath);

  const sha256 = crypto
    .createHash('sha256')
    .update(buffer)
    .digest('hex');

  return {
    zipPath: filePath,
    sizeBytes: buffer.length,
    sha256,
  };
}

async function getNextVersion(Model) {
  const latest = await Model.findOne({
    name: MODEL_NAME,
  }).sort({ version: -1 });

  if (!latest) {
    return 1;
  }

  return Number(latest.version) + 1;
}

async function publishToDatabase(dbUri, manifest) {
  const isAtlas = dbUri.includes('mongodb+srv');

  console.log(
    `\nConnecting to ${isAtlas ? 'MongoDB Atlas' : 'Local MongoDB'}...`
  );

  const conn = await mongoose.createConnection(dbUri).asPromise();

  try {
    const Model = conn.model('MlModel', MlModel.schema);

    // Find existing model
    const existing = await Model.findOne({
      name: MODEL_NAME,
    });

    // Automatically increment version
    const nextVersion = existing
      ? Number(existing.version || 0) + 1
      : 1;

    const finalManifest = {
      ...manifest,
      version: nextVersion,
      active: true,
    };

    // Update existing model, or create it if it doesn't exist
    const doc = await Model.findOneAndUpdate(
      {
        name: MODEL_NAME,
      },
      {
        $set: finalManifest,
      },
      {
        new: true,
        upsert: true,
        setDefaultsOnInsert: true,
      }
    );

    console.log(
      `Published ${MODEL_NAME} v${doc.version} to ${
        isAtlas ? 'MongoDB Atlas' : 'Local MongoDB'
      }`
    );

    console.log(`Active: ${doc.active}`);
    console.log(`URL: ${doc.url}`);

    return doc;
  } finally {
    await conn.close();
  }
}

